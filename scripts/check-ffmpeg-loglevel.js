#!/usr/bin/env node
/**
 * hold the trim path to the thing that broke it: ffmpeg must not be run quiet.
 *
 * a trimmed download is not yt-dlp downloading and ffmpeg cutting afterwards -
 * --download-sections hands the *fetch itself* to yt-dlp's ffmpeg downloader.
 * so whatever loglevel yt-dlp passes ffmpeg governs whether the download that
 * is actually happening can report progress or name its own failure. --print
 * implies --quiet, and that quiet reaches ffmpeg as `-loglevel quiet`: the
 * no-output watchdog then kills any trim longer than its deadline, and a real
 * error arrives as a bare exit code with ffmpeg's reason discarded.
 *
 * this asserts the fix against the real binaries rather than against a unit
 * test's idea of them, which is the whole point - the claim being tested is
 * about what a specific yt-dlp build does with a flag, and only that build can
 * answer it. it runs on any platform, so windows CI can answer it for windows.
 *
 * everything is local. the clip is generated by the bundled ffmpeg and served
 * from 127.0.0.1, because every public test asset tried first was either 403
 * or behind a cloudflare bot check - a check that fails when someone else's
 * CDN is having a day is not a check, and CI runner IPs attract exactly that.
 *
 * the control variant is not decoration. it strips --no-quiet back off and
 * requires that the same command *does* come out quiet: without it, a yt-dlp
 * that stopped emitting the debug line at all would pass silently forever.
 */

const { spawn, spawnSync } = require("child_process")
const http = require("http")
const path = require("path")
const os = require("os")
const fs = require("fs")

const {
  buildCommonArgs,
  buildDownloadArgs,
  buildTrimArgs,
  resolveExecutableIn
} = require("../src/main/services/ytdlp-engine")

const PLATFORM_DIRS = { darwin: "macos", win32: "windows", linux: "linux" }

// yt-dlp prints this under --verbose, right before it hands over to ffmpeg.
//
// it names the binary by its *basename*, so windows says "ffmpeg.exe command
// line:" where macos says "ffmpeg command line:" - matching the bare word cost
// a full CI round trip, and matching a fixed extension would cost the next one
const COMMAND_LINE_MARKER = /\bffmpeg\S*\s+command line:/i

// give up rather than hang a CI job forever if the marker never arrives
const TIMEOUT_MS = 90 * 1000

function repoPath(...parts) {
  return path.join(__dirname, "..", ...parts)
}

function resolveBinaries() {
  const dir = PLATFORM_DIRS[process.platform] || process.platform
  const engine = resolveExecutableIn(repoPath("binaries", dir, "ytdlp"))
  const ffmpegName = process.platform === "win32" ? "ffmpeg.exe" : "ffmpeg"
  const ffmpeg = repoPath("binaries", dir, ffmpegName)

  if (!engine) {
    throw new Error(`no yt-dlp under binaries/${dir}/ytdlp - run npm run fetch:ytdlp`)
  }
  if (!fs.existsSync(ffmpeg)) {
    throw new Error(`no ffmpeg at ${ffmpeg}`)
  }

  return { engine, ffmpeg }
}

/**
 * a few seconds of colour bars, made by the same ffmpeg the app ships
 * @param {string} ffmpeg - ffmpeg executable
 * @param {string} target - where to write the clip
 */
function makeClip(ffmpeg, target) {
  const result = spawnSync(
    ffmpeg,
    [
      "-y",
      "-f",
      "lavfi",
      "-i",
      "testsrc=duration=10:size=320x240:rate=10",
      "-c:v",
      "libx264",
      "-pix_fmt",
      "yuv420p",
      "-movflags",
      "+faststart",
      target
    ],
    { encoding: "utf8" }
  )

  if (result.status !== 0 || !fs.existsSync(target)) {
    const detail = (result.stderr || "").split("\n").slice(-5).join("\n")
    throw new Error(`could not build the test clip with ${ffmpeg}\n${detail}`)
  }
}

/**
 * serve one file, with the range support ffmpeg expects of an http source
 * @param {string} file - the clip to serve
 * @returns {Promise<{url: string, close: () => void}>} where it is served
 */
function serve(file) {
  const size = fs.statSync(file).size

  const server = http.createServer((req, res) => {
    const range = /^bytes=(\d*)-(\d*)$/.exec(req.headers.range || "")
    const head = {
      "Content-Type": "video/mp4",
      "Accept-Ranges": "bytes"
    }

    if (range) {
      const start = range[1] ? parseInt(range[1], 10) : 0
      const end = range[2] ? parseInt(range[2], 10) : size - 1
      res.writeHead(206, {
        ...head,
        "Content-Range": `bytes ${start}-${end}/${size}`,
        "Content-Length": end - start + 1
      })
      if (req.method === "HEAD") return res.end()
      return fs.createReadStream(file, { start, end }).pipe(res)
    }

    res.writeHead(200, { ...head, "Content-Length": size })
    if (req.method === "HEAD") return res.end()
    return fs.createReadStream(file).pipe(res)
  })

  return new Promise((resolve) => {
    // port 0 - let the OS pick, so parallel jobs never collide
    server.listen(0, "127.0.0.1", () => {
      const { port } = server.address()
      resolve({
        url: `http://127.0.0.1:${port}/clip.mp4`,
        close: () => server.close()
      })
    })
  })
}

/**
 * run yt-dlp far enough to see the ffmpeg command it builds, then stop it
 *
 * we do not want the download - we want the command line. so the child is
 * killed the moment the marker lands.
 *
 * @param {string} engine - yt-dlp executable
 * @param {string[]} args - the full argument list
 * @returns {Promise<{line: string|null, tail: string[]}>} what was seen
 */
function ffmpegCommandLine(engine, args) {
  return new Promise((resolve, reject) => {
    const child = spawn(engine, args, { stdio: ["ignore", "pipe", "pipe"] })

    let found = null
    let buffer = ""
    let done = false
    const tail = []

    const finish = (error) => {
      if (done) return
      done = true
      clearTimeout(timer)
      try {
        child.kill()
      } catch {
        // already gone - the command line is what we came for either way
      }
      if (error) reject(error)
      else resolve({ line: found, tail })
    }

    const timer = setTimeout(() => finish(), TIMEOUT_MS)

    // the marker can land on either stream depending on build, so watch both
    const scan = (chunk) => {
      buffer += chunk
      const lines = buffer.split(/\r\n|\r|\n/)
      buffer = lines.pop()
      for (const line of lines) {
        // kept so a failure can say why, rather than only that nothing matched
        tail.push(line)
        if (tail.length > 12) tail.shift()

        if (COMMAND_LINE_MARKER.test(line)) {
          found = line
          finish()
          return
        }
      }
    }

    child.stdout.setEncoding("utf8")
    child.stderr.setEncoding("utf8")
    child.stdout.on("data", scan)
    child.stderr.on("data", scan)

    child.on("error", (error) => finish(error))
    child.on("close", () => finish())
  })
}

async function main() {
  const { engine, ffmpeg } = resolveBinaries()

  const workDir = fs.mkdtempSync(path.join(os.tmpdir(), "cliply-loglevel-"))
  const clip = path.join(workDir, "source.mp4")

  console.log(`platform : ${process.platform}`)
  console.log(`engine   : ${engine}`)
  console.log(`ffmpeg   : ${ffmpeg}`)

  makeClip(ffmpeg, clip)
  const { url, close } = await serve(clip)
  console.log(`serving  : ${url}\n`)

  // a directory per variant, never a shared one: the first run leaves a file
  // behind, and yt-dlp answers the second with "has already been downloaded"
  // and never invokes ffmpeg at all - which reads exactly like the marker
  // being absent, and would quietly turn the control into a false alarm
  const shippedDir = fs.mkdtempSync(path.join(workDir, "shipped-"))
  const controlDir = fs.mkdtempSync(path.join(workDir, "control-"))

  // the app's own builders, not a copy of them - if the shipped arg list stops
  // carrying --no-quiet this has to fail, and a hand-written command would not
  const argsFor = (outputDir) => [
    ...buildCommonArgs({ ffmpegPath: ffmpeg }),
    ...buildDownloadArgs({ outputDir }),
    ...buildTrimArgs({ timeRange: { start: 0, end: 2 } }),
    "--verbose",
    url
  ]

  const shipped = argsFor(shippedDir)

  // same command with the fix backed out
  const control = argsFor(controlDir).filter((arg) => arg !== "--no-quiet")

  if (shipped.length === control.length) {
    close()
    throw new Error("buildDownloadArgs no longer emits --no-quiet")
  }

  const shippedRun = await ffmpegCommandLine(engine, shipped)
  const controlRun = await ffmpegCommandLine(engine, control)

  close()
  fs.rmSync(workDir, { recursive: true, force: true })

  // never print the command line itself: yt-dlp bakes any response cookies it
  // picked up into ffmpeg's -cookies argument, and CI logs are public on a
  // public repo. the loglevel is the entire subject of this check anyway
  const loglevelOf = (line) => {
    if (!line) return "(no ffmpeg command line seen)"
    const match = line.match(/-loglevel\s+(\S+)/)
    return match ? match[1] : "(no -loglevel in command)"
  }

  console.log(`shipped  : -loglevel ${loglevelOf(shippedRun.line)}`)
  console.log(`control  : -loglevel ${loglevelOf(controlRun.line)}\n`)

  const failures = []

  if (!shippedRun.line) {
    failures.push("shipped args never reached ffmpeg - could not verify anything")
  } else if (/-loglevel\s+quiet/.test(shippedRun.line)) {
    failures.push("shipped args still run ffmpeg with -loglevel quiet")
  }

  // the control proves the assertion above can fail. without it, a yt-dlp that
  // never printed the marker would look like a pass
  if (!controlRun.line) {
    failures.push("control never reached ffmpeg - the check cannot prove itself")
  } else if (!/-loglevel\s+quiet/.test(controlRun.line)) {
    failures.push(
      "control did NOT come out quiet - --print no longer implies --quiet on " +
        "this build, so this check is no longer testing the bug it was written for"
    )
  }

  if (failures.length) {
    console.error("FAIL")
    for (const failure of failures) {
      console.error(`  - ${failure}`)
    }
    for (const [name, run] of [
      ["shipped", shippedRun],
      ["control", controlRun]
    ]) {
      if (!run.line) {
        console.error(`\nlast lines from the ${name} run:`)
        for (const line of run.tail) console.error(`  ${line}`)
      }
    }
    process.exit(1)
  }

  console.log("PASS - ffmpeg runs audible with the shipped args, quiet without")
}

main().catch((error) => {
  console.error(`FAIL - ${error && error.message ? error.message : error}`)
  process.exit(1)
})
